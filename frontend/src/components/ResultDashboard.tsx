import React, { useState } from 'react';
import {
  Copy,
  Check,
  Download,
  RefreshCw,
  Edit3,
  Clock,
  Code2,
  PenTool,
  BookOpen,
  Image as ImageIcon,
  BarChart3,
  Sparkles,
  Layers,
  FileText,
  Lightbulb,
  CheckCircle2,
  Zap,
} from 'lucide-react';
import type { PromptResponse } from '../types';

interface ResultDashboardProps {
  result: PromptResponse;
  onRegenerate: () => void;
  onEdit: () => void;
}

export const ResultDashboard: React.FC<ResultDashboardProps> = ({
  result,
  onRegenerate,
  onEdit,
}) => {
  const [copied, setCopied] = useState(false);
  const [activeTab, setActiveTab] = useState<'all' | 'persona' | 'context' | 'task' | 'constraints' | 'output_format'>('all');
  const [showComparison, setShowComparison] = useState(false);

  const {
    original_prompt,
    detected_intent,
    applied_intent,
    confidence,
    is_overridden,
    refined_prompt,
    structured_breakdown,
    suggestions,
    processing_time_ms,
  } = result;

  const originalWords = original_prompt.trim().split(/\s+/).filter(Boolean).length;
  const refinedWords = refined_prompt.trim().split(/\s+/).filter(Boolean).length;
  const expansionRatio = originalWords > 0 ? (refinedWords / originalWords).toFixed(1) : '1.0';
  const estimatedTokens = Math.round(refinedWords * 1.33);

  const getCategoryDetails = (intentName: string) => {
    switch (intentName) {
      case 'Coding':
        return { color: '#3b82f6', bg: 'rgba(59, 130, 246, 0.15)', border: 'rgba(59, 130, 246, 0.35)', icon: <Code2 size={16} color="#3b82f6" /> };
      case 'Writing':
        return { color: '#8b5cf6', bg: 'rgba(139, 92, 246, 0.15)', border: 'rgba(139, 92, 246, 0.35)', icon: <PenTool size={16} color="#8b5cf6" /> };
      case 'Education':
        return { color: '#f59e0b', bg: 'rgba(245, 158, 11, 0.15)', border: 'rgba(245, 158, 11, 0.35)', icon: <BookOpen size={16} color="#f59e0b" /> };
      case 'Image Generation':
        return { color: '#ec4899', bg: 'rgba(236, 72, 153, 0.15)', border: 'rgba(236, 72, 153, 0.35)', icon: <ImageIcon size={16} color="#ec4899" /> };
      case 'Data Analysis':
        return { color: '#10b981', bg: 'rgba(16, 185, 129, 0.15)', border: 'rgba(16, 185, 129, 0.35)', icon: <BarChart3 size={16} color="#10b981" /> };
      default:
        return { color: '#a78bfa', bg: 'rgba(167, 139, 250, 0.15)', border: 'rgba(167, 139, 250, 0.35)', icon: <Sparkles size={16} /> };
    }
  };

  const currentCategory = getCategoryDetails(applied_intent || detected_intent);

  const handleCopy = () => {
    navigator.clipboard.writeText(refined_prompt);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownload = () => {
    const timestamp = new Date().toISOString().split('T')[0];
    const categorySlug = (applied_intent || 'prompt').toLowerCase().replace(/\s+/g, '-');
    const filename = `smartprompt-${categorySlug}-${timestamp}.md`;

    const markdownContent = `# SmartPrompt Optimized Prompt
**Category / Intent:** ${applied_intent} (Model Detected: ${detected_intent})  
**Confidence Score:** ${(confidence * 100).toFixed(1)}%  
**Processing Latency:** ${processing_time_ms} ms  
**Date:** ${new Date().toLocaleString()}  

---

## 🎯 Refined Production Prompt
\`\`\`markdown
${refined_prompt}
\`\`\`

---

## 📋 Structured Breakdown
- **Persona:** ${structured_breakdown.persona || 'N/A'}
- **Context:** ${structured_breakdown.context || 'N/A'}
- **Core Task:** ${structured_breakdown.task || 'N/A'}
- **Constraints:** ${structured_breakdown.constraints || 'N/A'}
- **Output Format:** ${structured_breakdown.output_format || 'N/A'}

---

## 💡 Suggestions & Optimization Rationale
${suggestions.map((s, i) => `${i + 1}. ${s}`).join('\n')}

---
*Generated by SmartPrompt (LinearSVC ML Classifier + NLP Pipeline)*
`;

    const blob = new Blob([markdownContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);
  };

  return (
    <section id="results" style={{ paddingTop: '20px', paddingBottom: '64px' }}>
      <div className="container" style={{ maxWidth: '1040px' }}>
        
        {/* Top Summary Banner Card */}
        <div
          className="glass-card"
          style={{
            padding: '24px',
            marginBottom: '24px',
            background: 'rgba(10, 15, 29, 0.85)',
            border: `1px solid ${currentCategory.border}`,
            boxShadow: `0 8px 32px -4px ${currentCategory.bg}`,
          }}
        >
          <div
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              flexWrap: 'wrap',
              gap: '16px',
            }}
          >
            {/* Left: Intent and override information */}
            <div style={{ display: 'flex', alignItems: 'center', gap: '14px', flexWrap: 'wrap' }}>
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: '8px',
                  background: currentCategory.bg,
                  border: `1px solid ${currentCategory.border}`,
                  padding: '6px 14px',
                  borderRadius: '100px',
                  color: currentCategory.color,
                  fontWeight: 700,
                  fontSize: '0.875rem',
                }}
              >
                {currentCategory.icon}
                <span>Intent: {applied_intent}</span>
              </div>

              {is_overridden && (
                <span
                  style={{
                    fontSize: '0.75rem',
                    background: 'rgba(245, 158, 11, 0.15)',
                    border: '1px solid rgba(245, 158, 11, 0.35)',
                    color: '#fbbf24',
                    padding: '3px 8px',
                    borderRadius: '6px',
                    fontWeight: 600,
                  }}
                >
                  User Override (ML Predicted: {detected_intent})
                </span>
              )}
            </div>

            {/* Right: Metrics Pills (Confidence, Latency, Word Expansion) */}
            <div style={{ display: 'flex', alignItems: 'center', gap: '12px', flexWrap: 'wrap' }}>
              {/* Confidence Badge */}
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: '6px',
                  background: 'rgba(255, 255, 255, 0.04)',
                  border: '1px solid var(--border-subtle)',
                  padding: '5px 12px',
                  borderRadius: '8px',
                  fontSize: '0.78rem',
                }}
                title="LinearSVC Decision Function Confidence Score"
              >
                <Zap size={14} color="#22d3ee" />
                <span style={{ color: 'var(--text-muted)' }}>Confidence:</span>
                <span style={{ fontWeight: 700, color: '#22d3ee' }}>
                  {(confidence * 100).toFixed(1)}%
                </span>
              </div>

              {/* Latency Badge */}
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: '6px',
                  background: 'rgba(255, 255, 255, 0.04)',
                  border: '1px solid var(--border-subtle)',
                  padding: '5px 12px',
                  borderRadius: '8px',
                  fontSize: '0.78rem',
                }}
                title="Total pipeline execution latency"
              >
                <Clock size={14} color="#10b981" />
                <span style={{ color: 'var(--text-muted)' }}>Latency:</span>
                <span style={{ fontWeight: 700, color: '#10b981' }}>
                  {processing_time_ms} ms
                </span>
              </div>

              {/* Expansion Multiplier */}
              <div
                style={{
                  display: 'flex',
                  alignItems: 'center',
                  gap: '6px',
                  background: 'rgba(255, 255, 255, 0.04)',
                  border: '1px solid var(--border-subtle)',
                  padding: '5px 12px',
                  borderRadius: '8px',
                  fontSize: '0.78rem',
                }}
                title="Length expansion from input to structured prompt"
              >
                <Layers size={14} color="var(--primary)" />
                <span style={{ color: 'var(--text-muted)' }}>Expansion:</span>
                <span style={{ fontWeight: 700, color: 'var(--primary)' }}>
                  {expansionRatio}x ({refinedWords} words)
                </span>
              </div>
            </div>
          </div>
        </div>

        {/* Action Toolbar */}
        <div
          style={{
            display: 'flex',
            alignItems: 'center',
            justifyContent: 'space-between',
            marginBottom: '16px',
            flexWrap: 'wrap',
            gap: '12px',
          }}
        >
          <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
            <button
              onClick={() => setShowComparison(!showComparison)}
              className="btn-secondary"
              style={{
                fontSize: '0.8rem',
                padding: '6px 14px',
                background: showComparison ? 'rgba(139, 92, 246, 0.2)' : undefined,
                borderColor: showComparison ? 'var(--primary)' : undefined,
              }}
            >
              <span>{showComparison ? 'Hide Comparison' : 'Compare Before & After'}</span>
            </button>
          </div>

          <div style={{ display: 'flex', alignItems: 'center', gap: '8px', flexWrap: 'wrap' }}>
            <button
              onClick={onEdit}
              className="btn-secondary"
              style={{ fontSize: '0.8rem', padding: '6px 14px' }}
              title="Return to input box to edit your request"
            >
              <Edit3 size={14} />
              <span>Edit Input</span>
            </button>

            <button
              onClick={onRegenerate}
              className="btn-secondary"
              style={{ fontSize: '0.8rem', padding: '6px 14px' }}
              title="Re-run classification and refinement"
            >
              <RefreshCw size={14} />
              <span>Regenerate</span>
            </button>

            <button
              onClick={handleDownload}
              className="btn-secondary"
              style={{ fontSize: '0.8rem', padding: '6px 14px' }}
              title="Download formatted prompt as Markdown"
            >
              <Download size={14} />
              <span>Export .md</span>
            </button>

            <button
              onClick={handleCopy}
              className="btn-primary"
              style={{
                fontSize: '0.85rem',
                padding: '7px 18px',
                background: copied ? 'rgba(16, 185, 129, 0.9)' : undefined,
                boxShadow: copied ? '0 0 16px rgba(16, 185, 129, 0.4)' : undefined,
              }}
            >
              {copied ? (
                <>
                  <Check size={16} />
                  <span>Copied to Clipboard!</span>
                </>
              ) : (
                <>
                  <Copy size={16} />
                  <span>Copy Prompt</span>
                </>
              )}
            </button>
          </div>
        </div>

        {/* Before / After Comparison Drawer */}
        {showComparison && (
          <div
            className="glass-card"
            style={{
              padding: '20px',
              marginBottom: '20px',
              background: 'rgba(5, 6, 10, 0.95)',
              border: '1px solid rgba(255, 255, 255, 0.1)',
            }}
          >
            <div
              style={{
                display: 'grid',
                gridTemplateColumns: 'repeat(auto-fit, minmax(300px, 1fr))',
                gap: '16px',
              }}
            >
              <div
                style={{
                  padding: '16px',
                  background: 'rgba(239, 68, 68, 0.05)',
                  border: '1px solid rgba(239, 68, 68, 0.2)',
                  borderRadius: '8px',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#f87171', marginBottom: '8px', textTransform: 'uppercase' }}>
                  Original Input ({originalWords} words)
                </div>
                <p style={{ fontSize: '0.9rem', color: 'var(--text-secondary)', lineHeight: 1.6, margin: 0 }}>
                  {original_prompt}
                </p>
              </div>

              <div
                style={{
                  padding: '16px',
                  background: 'rgba(16, 185, 129, 0.05)',
                  border: '1px solid rgba(16, 185, 129, 0.2)',
                  borderRadius: '8px',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#34d399', marginBottom: '8px', textTransform: 'uppercase' }}>
                  Production Optimized ({refinedWords} words · {expansionRatio}x expansion)
                </div>
                <div style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', lineHeight: 1.6 }}>
                  Structured with Persona, Constraints, Validation Rules, and Markdown Output format ready for leading LLMs.
                </div>
              </div>
            </div>
          </div>
        )}

        {/* Main Production Prompt Display Card */}
        <div
          className="glass-card"
          style={{
            padding: '28px',
            marginBottom: '24px',
            background: 'rgba(8, 12, 22, 0.9)',
            border: '1px solid rgba(139, 92, 246, 0.25)',
          }}
        >
          {/* Header Bar of the Prompt Card */}
          <div
            style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              paddingBottom: '16px',
              marginBottom: '20px',
              borderBottom: '1px solid var(--border-subtle)',
              flexWrap: 'wrap',
              gap: '12px',
            }}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
              <FileText size={18} color="var(--primary)" />
              <h3 style={{ fontSize: '1.05rem', margin: 0, fontWeight: 700 }}>
                Refined Production Prompt
              </h3>
            </div>

            <div style={{ display: 'flex', alignItems: 'center', gap: '14px', fontSize: '0.75rem', color: 'var(--text-muted)' }}>
              <span>{refinedWords} words</span>
              <span>•</span>
              <span>{refined_prompt.length} chars</span>
              <span>•</span>
              <span>~{estimatedTokens} tokens</span>
            </div>
          </div>

          {/* Prompt Body */}
          <div
            style={{
              fontFamily: 'var(--font-mono)',
              fontSize: '0.9rem',
              lineHeight: 1.7,
              color: '#e2e8f0',
              whiteSpace: 'pre-wrap',
              background: 'rgba(5, 6, 10, 0.6)',
              padding: '20px',
              borderRadius: '10px',
              border: '1px solid rgba(255, 255, 255, 0.05)',
              maxHeight: '480px',
              overflowY: 'auto',
            }}
          >
            {refined_prompt}
          </div>
        </div>

        {/* Structured Breakdown Section */}
        <div
          className="glass-card"
          style={{
            padding: '24px',
            marginBottom: '24px',
            background: 'rgba(10, 15, 29, 0.85)',
          }}
        >
          <div style={{ marginBottom: '16px' }}>
            <h3 style={{ fontSize: '1.1rem', marginBottom: '6px' }}>
              Structured Prompt Architecture
            </h3>
            <p style={{ fontSize: '0.85rem', color: 'var(--text-secondary)', margin: 0 }}>
              The prompt is modularized into 5 foundational components for maximum LLM adherence and reliability:
            </p>
          </div>

          {/* Tabs */}
          <div
            style={{
              display: 'flex',
              gap: '6px',
              borderBottom: '1px solid var(--border-subtle)',
              paddingBottom: '12px',
              marginBottom: '20px',
              overflowX: 'auto',
            }}
          >
            {[
              { id: 'all', label: 'All Components' },
              { id: 'persona', label: '1. Persona' },
              { id: 'context', label: '2. Context' },
              { id: 'task', label: '3. Task' },
              { id: 'constraints', label: '4. Constraints' },
              { id: 'output_format', label: '5. Output Format' },
            ].map((tab) => (
              <button
                key={tab.id}
                onClick={() => setActiveTab(tab.id as any)}
                style={{
                  background: activeTab === tab.id ? 'rgba(139, 92, 246, 0.2)' : 'transparent',
                  color: activeTab === tab.id ? '#ffffff' : 'var(--text-secondary)',
                  border: activeTab === tab.id ? '1px solid var(--primary)' : '1px solid transparent',
                  borderRadius: '6px',
                  padding: '6px 12px',
                  fontSize: '0.78rem',
                  fontWeight: activeTab === tab.id ? 600 : 500,
                  cursor: 'pointer',
                  whiteSpace: 'nowrap',
                  transition: 'all 0.15s ease',
                }}
              >
                {tab.label}
              </button>
            ))}
          </div>

          {/* Breakdown Items */}
          <div style={{ display: 'flex', flexDirection: 'column', gap: '14px' }}>
            {(activeTab === 'all' || activeTab === 'persona') && structured_breakdown.persona && (
              <div
                style={{
                  padding: '14px 18px',
                  background: 'rgba(59, 130, 246, 0.05)',
                  borderLeft: '3px solid #3b82f6',
                  borderRadius: '0 8px 8px 0',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#60a5fa', textTransform: 'uppercase', marginBottom: '4px' }}>
                  Target Persona &amp; Role
                </div>
                <p style={{ margin: 0, fontSize: '0.88rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                  {structured_breakdown.persona}
                </p>
              </div>
            )}

            {(activeTab === 'all' || activeTab === 'context') && structured_breakdown.context && (
              <div
                style={{
                  padding: '14px 18px',
                  background: 'rgba(139, 92, 246, 0.05)',
                  borderLeft: '3px solid #8b5cf6',
                  borderRadius: '0 8px 8px 0',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#a78bfa', textTransform: 'uppercase', marginBottom: '4px' }}>
                  Background Context &amp; Objective
                </div>
                <p style={{ margin: 0, fontSize: '0.88rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                  {structured_breakdown.context}
                </p>
              </div>
            )}

            {(activeTab === 'all' || activeTab === 'task') && structured_breakdown.task && (
              <div
                style={{
                  padding: '14px 18px',
                  background: 'rgba(236, 72, 153, 0.05)',
                  borderLeft: '3px solid #ec4899',
                  borderRadius: '0 8px 8px 0',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#f472b6', textTransform: 'uppercase', marginBottom: '4px' }}>
                  Core Functional Task
                </div>
                <p style={{ margin: 0, fontSize: '0.88rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                  {structured_breakdown.task}
                </p>
              </div>
            )}

            {(activeTab === 'all' || activeTab === 'constraints') && structured_breakdown.constraints && (
              <div
                style={{
                  padding: '14px 18px',
                  background: 'rgba(245, 158, 11, 0.05)',
                  borderLeft: '3px solid #f59e0b',
                  borderRadius: '0 8px 8px 0',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#fbbf24', textTransform: 'uppercase', marginBottom: '4px' }}>
                  Quality Criteria &amp; Guardrails
                </div>
                <p style={{ margin: 0, fontSize: '0.88rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                  {structured_breakdown.constraints}
                </p>
              </div>
            )}

            {(activeTab === 'all' || activeTab === 'output_format') && structured_breakdown.output_format && (
              <div
                style={{
                  padding: '14px 18px',
                  background: 'rgba(16, 185, 129, 0.05)',
                  borderLeft: '3px solid #10b981',
                  borderRadius: '0 8px 8px 0',
                }}
              >
                <div style={{ fontSize: '0.75rem', fontWeight: 700, color: '#34d399', textTransform: 'uppercase', marginBottom: '4px' }}>
                  Prescribed Output Format
                </div>
                <p style={{ margin: 0, fontSize: '0.88rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                  {structured_breakdown.output_format}
                </p>
              </div>
            )}
          </div>
        </div>

        {/* Suggestions & Optimization Tips */}
        {suggestions && suggestions.length > 0 && (
          <div
            className="glass-card"
            style={{
              padding: '24px',
              background: 'rgba(10, 15, 29, 0.85)',
            }}
          >
            <div style={{ display: 'flex', alignItems: 'center', gap: '8px', marginBottom: '14px' }}>
              <Lightbulb size={18} color="#fbbf24" />
              <h3 style={{ fontSize: '1.05rem', margin: 0 }}>
                Optimization Rationale &amp; LLM Execution Tips
              </h3>
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))', gap: '12px' }}>
              {suggestions.map((suggestion, idx) => (
                <div
                  key={idx}
                  style={{
                    display: 'flex',
                    alignItems: 'flex-start',
                    gap: '10px',
                    padding: '12px',
                    background: 'rgba(255, 255, 255, 0.02)',
                    border: '1px solid var(--border-subtle)',
                    borderRadius: '8px',
                  }}
                >
                  <CheckCircle2 size={16} color="var(--primary)" style={{ flexShrink: 0, marginTop: '2px' }} />
                  <span style={{ fontSize: '0.825rem', color: 'var(--text-secondary)', lineHeight: 1.5 }}>
                    {suggestion}
                  </span>
                </div>
              ))}
            </div>
          </div>
        )}

      </div>
    </section>
  );
};
